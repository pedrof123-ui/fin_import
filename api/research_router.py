_ML_COMPS_MAX_MULTIPLE = 500.0  # matches scripts/score_ml_comps_valuation.py's sanity cap
_ML_COMPS_COLS = [
    "ml_fair_price_low", "ml_fair_price_mid", "ml_fair_price_high", "ml_fair_price_basis",
    "ml_fair_pe_low", "ml_fair_pe_mid", "ml_fair_pe_high",
    "ml_fair_pfcf_low", "ml_fair_pfcf_mid", "ml_fair_pfcf_high",
    "ml_fair_ps_low", "ml_fair_ps_mid", "ml_fair_ps_high",
]


def _get_ml_comps_data(ticker: str) -> Optional[dict]:
    """Single DB read of the `ml_comps_valuation` row for `ticker` (PLAN_ML_COMPS_TRIANGULATION.md
    Phase 0/1), shared by _ml_comps_row (display table, Phase 1) and _format_ml_comps_summary
    (Valuation Analyst context, Phase 2) so the capped-multiple detection logic lives in exactly
    one place. Returns None when the DB/ticker/`status='ok'` row is missing. Adds two derived
    keys: `contributing` (the multiples named in `ml_fair_price_basis`, e.g. ["pe","pfcf","ps"])
    and `capped` (True if any *contributing* multiple's high hit the scoring script's sanity cap
    — Phase 0.2's ACHR finding: this collapses `ml_fair_price` into a near-worthless dollar
    figure for near-zero-revenue/negative-earnings names, directionally correct but not a usable
    absolute anchor). Exact float equality against 500.0 doesn't hold — the cap round-trips
    through log/exp in the scoring script and lands at 499.99999999999983 — hence the tolerance."""
    if not _HIST_FUND_DB.exists():
        return None
    try:
        conn = duckdb.connect(str(_HIST_FUND_DB), read_only=True)
        row = conn.execute(
            f"""SELECT {", ".join(_ML_COMPS_COLS)}
                FROM ml_comps_valuation WHERE ticker = ? AND status = 'ok'""",
            [ticker.upper()],
        ).fetchone()
        conn.close()
    except Exception:
        return None
    if not row:
        return None
    data = dict(zip(_ML_COMPS_COLS, row))
    if (
        data["ml_fair_price_low"] is None or data["ml_fair_price_mid"] is None
        or data["ml_fair_price_high"] is None or not data["ml_fair_price_basis"]
    ):
        return None
    highs = {"pe": data["ml_fair_pe_high"], "pfcf": data["ml_fair_pfcf_high"], "ps": data["ml_fair_ps_high"]}
    contributing = [
        m.strip() for m in data["ml_fair_price_basis"].removeprefix("median(").removesuffix(")").split(",")
    ]
    data["contributing"] = contributing
    data["capped"] = any(
        highs.get(m) is not None and highs[m] >= _ML_COMPS_MAX_MULTIPLE - 1e-6 for m in contributing
    )
    return data


def _ml_comps_row(ticker: str) -> Optional[list[str]]:
    """Row for _model_summary_table: peer-relative ML comps fair value. Omitted entirely (not
    "n/a") when unavailable or capped — see _get_ml_comps_data."""
    data = _get_ml_comps_data(ticker)
    if data is None or data["capped"]:
        return None
    return [
        "ML Comps (peer-relative)",
        f"${data['ml_fair_price_low']:.2f}", f"${data['ml_fair_price_mid']:.2f}", f"${data['ml_fair_price_high']:.2f}",
    ]


def _format_ml_comps_summary(ticker: str) -> str:
    """ML comps-based fair valuation for the Valuation Analyst's context
    (PLAN_ML_COMPS_TRIANGULATION.md Phase 2) — a peer cross-sectional XGBoost quantile model,
    independent of both DCF paradigms and the ticker's-own-history Multiples cross-check.
    Degrades to an [INFO] placeholder when unavailable, mirroring format_ai_dcf_summary(None).
    Unlike the display row, a capped prediction is NOT hidden here — it's surfaced with an
    explicit low-confidence flag so the analyst can use it as directional evidence."""
    data = _get_ml_comps_data(ticker)
    if data is None:
        return "[INFO] ML comps valuation unavailable for this run — proceed without this anchor"

    def _mult_line(label, key):
        lo, mid, hi = data[f"ml_fair_{key}_low"], data[f"ml_fair_{key}_mid"], data[f"ml_fair_{key}_high"]
        if lo is None or mid is None or hi is None:
            return None
        return f"{label}: p10={lo:.1f}x  p50={mid:.1f}x  p90={hi:.1f}x"

    lines = [
        f"ML COMPS-BASED FAIR VALUE — {ticker.upper()} (peer cross-sectional XGBoost quantile "
        "model, validated for P/E, P/FCF, P/S only — NOT the same as the normalized-history "
        "multiples in VALUATION INPUTS above, which compare the ticker to ITS OWN history; this "
        "compares it to SECTOR PEERS with similar fundamentals right now)",
        "",
    ]
    for label, key in [("Predicted fair P/E", "pe"), ("Predicted fair P/FCF", "pfcf"), ("Predicted fair P/S", "ps")]:
        line = _mult_line(label, key)
        if line:
            lines.append(line)
    lines += [
        "",
        f"Blended fair price (median across {', '.join(m.upper() for m in data['contributing'])} "
        f"bases, p10/p50/p90): ${data['ml_fair_price_low']:.2f} / ${data['ml_fair_price_mid']:.2f} "
        f"/ ${data['ml_fair_price_high']:.2f}",
    ]
    if data["capped"]:
        lines.append(
            "[CAPPED - LOW CONFIDENCE] one of the contributing predicted multiples hit the "
            "model's 500x sanity cap — this usually means near-zero trailing revenue/earnings "
            "relative to price (a pre-revenue or narrative-driven name). Treat this as "
            "directional evidence of rich peer-relative pricing only, not a precise dollar "
            "figure to average into fair_value_low/base/high."
        )
    lines.append(
        "Caveat: this reflects fair value RELATIVE TO PEERS — if the whole peer group is "
        "mispriced, this anchor inherits that mispricing rather than correcting for it."
    )
    return "\n".join(lines)


def _model_summary_table(
    ticker: str, scenarios: dict, pe_multiples: Optional[tuple], ps_multiples: Optional[tuple],
    pfcf_multiples: Optional[tuple],
    fair_value_low: float, fair_value_base: float, fair_value_high: float,
    ai_dcf_engine: Optional[dict] = None,
) -> str:
    rows = []
    bear, base, bull = scenarios.get("bear"), scenarios.get("base"), scenarios.get("bull")
    rows.append([
        "DCF (scenario)",
        f"${bear.intrinsic_value_per_share:.2f}" if bear else "n/a",
        f"${base.intrinsic_value_per_share:.2f}" if base else "n/a",
        f"${bull.intrinsic_value_per_share:.2f}" if bull else "n/a",
    ])
    if ai_dcf_engine is not None:
        # Agentic AI DCF Valuator (features/ai_dcf/SPEC.md) — a second, independent DCF row,
        # both computed by the same deterministic engine, never by an LLM.
        from api.ai_dcf_router import render_ai_dcf_triangulation_row
        rows.append(render_ai_dcf_triangulation_row(ai_dcf_engine))

    ml_comps_row = _ml_comps_row(ticker)
    if ml_comps_row is not None:
        # Peer-relative cross-sectional anchor (PLAN_ML_COMPS_TRIANGULATION.md) — distinct from
        # both DCF paradigms above and the ticker's-own-history Multiples rows below.
        rows.append(ml_comps_row)

    def _multiples_row(label, multiples):
        if not multiples or not all(v is not None for v in multiples):
            return None
        p25, med, p75, forward_metric = multiples
        return [
            label,
            f"${p25 * forward_metric:.2f}",
            f"${med * forward_metric:.2f}",
            f"${p75 * forward_metric:.2f}",
        ]

    # P/S first: the most broadly computable cross-check (revenue is defined even when
    # earnings/FCF aren't), followed by P/E and P/FCF where available.
    for label, multiples in [
        ("Multiples (P/S x Forward Revenue/Share)", ps_multiples),
        ("Multiples (P/E x Forward EPS)", pe_multiples),
        ("Multiples (P/FCF x Forward FCF/Share, est.)", pfcf_multiples),
    ]:
        row = _multiples_row(label, multiples)
        if row:
            rows.append(row)

    rows.append([
        "**Valuation Analyst Fair Value**",
        f"**${fair_value_low:.2f}**", f"**${fair_value_base:.2f}**", f"**${fair_value_high:.2f}**",
    ])
    lines = ["#### Model Summary — Fair Value Triangulation", ""]
    lines += _md_table(["Method", "Low", "Base", "High"], rows)
    return "\n".join(lines)


def render_valuation_model_tables(
    ticker: str, scenarios: dict, fair_value_low: float, fair_value_base: float, fair_value_high: float,
    ai_dcf_result=None,
) -> str:
    """Assembles the Valuation Model Detail tables. Every number here is computed in
    Python from the DCF engine / database — never authored by an LLM — so it can't drift from
    what the model actually produced. `scenarios` is the (already-computed) output of
    compute_dcf_scenarios — shared with render_market_share_table so the mechanical DCF only
    runs once. `ai_dcf_result` (an api.ai_dcf_router.AiDcfResult, or None if the AI DCF didn't
    run) adds a "DCF (AI-authored)" triangulation row and an "AI vs. Mechanical DCF Assumptions"
    comparison table — the AI DCF engine itself only ever runs inside the AI DCF pipeline
    (Phase 4), never re-run here."""
    fundamentals_md, pe_multiples, ps_multiples, pfcf_multiples = _fundamentals_table(ticker)
    ai_dcf_engine = ai_dcf_result.engine if ai_dcf_result is not None else None
    blocks = [
        _dcf_assumptions_table(scenarios),
        fundamentals_md,
        _comps_table(ticker),
        _model_summary_table(
            ticker, scenarios, pe_multiples, ps_multiples, pfcf_multiples,
            fair_value_low, fair_value_base, fair_value_high,
            ai_dcf_engine=ai_dcf_engine,
        ),
    ]
    if ai_dcf_engine is not None:
        from api.ai_dcf_router import render_ai_dcf_comparison_table
        blocks.append(render_ai_dcf_comparison_table(ai_dcf_engine, scenarios))
    return "### Valuation Model Detail\n\n" + "\n\n".join(b for b in blocks if b)


def render_direct_competitors_table(competitive) -> str:
    """LLM-identified direct competitors (product/customer overlap, may cross sector/industry
    classification) cross-checked against real financial data where the ticker exists in our
    DB. Distinct from the sector/industry-classified peer table used for relative valuation —
    that table is a mechanical classification match and can miss or misinclude competitors."""
    if not competitive.direct_competitors:
        return ""

    tickers = [c.ticker.upper() for c in competitive.direct_competitors if c.ticker]
    rows_by_ticker: dict[str, tuple] = {}
    if tickers and _HIST_FUND_DB.exists() and _AV_FIN_DB.exists():
        try:
            conn = duckdb.connect(":memory:")
            conn.execute(f"ATTACH '{_HIST_FUND_DB}' AS hf (READ_ONLY)")
            conn.execute(f"ATTACH '{_AV_FIN_DB}' AS av (READ_ONLY)")
            placeholders = ",".join("?" for _ in tickers)
            df = conn.execute(f"""
                WITH latest_co AS (
                    SELECT ticker, name, market_cap
                    FROM av.company_overview
                    QUALIFY ROW_NUMBER() OVER (PARTITION BY ticker ORDER BY fetch_date DESC) = 1
                )
                SELECT ps.ticker, co.name, COALESCE(ps.market_cap_b, co.market_cap / 1e9) AS market_cap_b,
                       ps.current_pe, ps.forward_pe, ps.rev_growth_1yr, ps.earn_growth_1yr, ps.current_roic
                FROM hf.pe_stats ps
                JOIN latest_co co ON ps.ticker = co.ticker
                WHERE ps.ticker IN ({placeholders})
            """, tickers).df()
            conn.close()
            rows_by_ticker = {r["ticker"]: r for _, r in df.iterrows()}
        except Exception:
            rows_by_ticker = {}

    def f(v, pct=False):
        if v is None or (isinstance(v, float) and (math.isnan(v) or math.isinf(v))):
            return "n/a"
        return f"{float(v) * 100:.1f}%" if pct else f"{float(v):.1f}"

    rows = []
    for c in competitive.direct_competitors:
        r = rows_by_ticker.get(c.ticker.upper()) if c.ticker else None
        if r is not None:
            rows.append([
                c.ticker, str(r["name"] or c.name)[:25], f(r["market_cap_b"]),
                f(r["current_pe"]), f(r["forward_pe"]),
                f(r["rev_growth_1yr"], pct=True), f(r["earn_growth_1yr"], pct=True),
                f(r["current_roic"], pct=True), c.why_direct,
            ])
        else:
            rows.append([c.ticker or "n/a", c.name, "n/a", "n/a", "n/a", "n/a", "n/a", "n/a", c.why_direct])

    lines = ["#### Direct Competitors (product/customer overlap — not industry classification)", ""]
    lines += _md_table(
        ["Ticker", "Company", "Mkt Cap $B", "P/E", "Fwd P/E", "Rev Gr", "Earn Gr", "ROIC", "Why Direct"],
        rows,
    )
    return "\n".join(lines)


def render_market_share_table(ticker: str, scenarios: Optional[dict], competitive) -> str:
    """Deterministic current/projected market share = actual (or DCF-forecasted) company
    revenue divided by the Competitive Analyst's web-search-grounded TAM range. The ratio math
    is done in code — never by the LLM — so it can't silently miscompute a percentage."""
    if competitive.tam_current_low is None and competitive.tam_projected_low is None:
        return ""

    current_revenue = None
    if _AV_FIN_DB.exists():
        conn = duckdb.connect(str(_AV_FIN_DB), read_only=True)
        row = conn.execute("""
            SELECT total_revenue FROM income_statements
            WHERE ticker = ? AND period_type = 'annual'
            ORDER BY fiscal_date_ending DESC LIMIT 1
        """, [ticker.upper()]).fetchone()
        conn.close()
        current_revenue = float(row[0]) if row and row[0] else None

    future_revenue = None
    base = scenarios.get("base") if scenarios else None
    if base is not None and len(base.year_forecasts) >= 5:
        future_revenue = base.year_forecasts[4].revenue

    def share_range(revenue, tam_low, tam_high):
        if not revenue or not tam_low or not tam_high or tam_low <= 0 or tam_high <= 0:
            return None, None
        lo = revenue / 1e9 / tam_high * 100
        hi = revenue / 1e9 / tam_low * 100
        return f"{lo:.2f}% – {hi:.2f}%", hi

    # A genuine independent 2030-ish estimate is essentially never bit-for-bit identical to
    # today's TAM figure — an exact match here means the Competitive Analyst almost certainly
    # failed to distinguish "current" from "projected" in an ambiguous search result and copied
    # the same range into both fields. Suppress only the corrupted projected figure; the current
    # row's math is independent and still correct.
    projected_is_duplicate = (
        competitive.tam_projected_low is not None and competitive.tam_current_low is not None
        and competitive.tam_projected_low == competitive.tam_current_low
        and competitive.tam_projected_high == competitive.tam_current_high
    )

    rows = []
    scope_warning = False
    if current_revenue and competitive.tam_current_low is not None and competitive.tam_current_high is not None:
        share, hi = share_range(current_revenue, competitive.tam_current_low, competitive.tam_current_high)
        if share:
            rows.append([
                "Current", f"${competitive.tam_current_low:.0f}B – ${competitive.tam_current_high:.0f}B",
                f"${current_revenue / 1e9:.1f}B", share,
            ])
            scope_warning = scope_warning or hi >= 90
    if (
        not projected_is_duplicate and future_revenue
        and competitive.tam_projected_low is not None and competitive.tam_projected_high is not None
    ):
        share, hi = share_range(future_revenue, competitive.tam_projected_low, competitive.tam_projected_high)
        if share:
            year_label = f"Projected ({competitive.tam_projected_year})" if competitive.tam_projected_year else "Projected"
            rows.append([
                year_label, f"${competitive.tam_projected_low:.0f}B – ${competitive.tam_projected_high:.0f}B",
                f"${future_revenue / 1e9:.1f}B (DCF base case, Year 5)", share,
            ])
            scope_warning = scope_warning or hi >= 90

    if not rows:
        return ""
    lines = ["#### Market Size & Share", ""]
    lines += _md_table(["Period", "TAM Range", "Company Revenue", "Estimated Market Share"], rows)
    if projected_is_duplicate:
        lines += [
            "",
            "*Note: the projected TAM range matched the current range exactly, which usually "
            "means the source data didn't clearly distinguish today's market size from a future "
            "estimate — omitted rather than shown as a misleading figure.*",
        ]
    if scope_warning:
        lines += [
            "",
            "*Note: an estimated share at or above ~90% usually signals the cited TAM is narrower "
            "than the company's total revenue base (a segment/product TAM rather than its full "
            "addressable business) rather than a genuine near-monopoly — read this range with "
            "that caveat.*",
        ]
    return "\n".join(lines)


def _build_post_subagent_tables(
    ticker: str, valuation_out, competitive_out, ai_dcf_result=None,
) -> tuple[str, str, str, Optional[float], Optional[float]]:
    """Builds the three deterministic tables that depend on sub-agent output (valuation model
    detail, direct competitors, market size & share), sharing a single DCF scenario computation
    between the two that need it. `ai_dcf_result` (Agentic AI DCF Valuator output, or None) is
    threaded into the valuation table only — it never triggers a second mechanical DCF run.

    Also returns the ground-truth mechanical base intrinsic value (from this same scenarios
    computation, not the Valuation Analyst's echoed `dcf_intrinsic_value` field) for the
    reconciliation audit trail (features/ai_dcf/SPEC.md 11) — reuses the one DCF run above
    rather than computing it again. And the ground-truth ML comps blended p50 fair price
    (PLAN_ML_COMPS_TRIANGULATION.md Phase 2), for the same echo-validation pattern applied to
    `ValuationOutput.ml_comps_fair_value` — a fresh, cheap single-row read since it isn't part
    of `scenarios`."""
    needs_valuation = valuation_out.fair_value_base != 0.0
    needs_market_share = competitive_out.tam_current_low is not None or competitive_out.tam_projected_low is not None

    scenarios = None
    if needs_valuation or needs_market_share:
        try:
            scenarios = compute_dcf_scenarios(ticker)
        except Exception:
            scenarios = None

    valuation_tables_md = (
        render_valuation_model_tables(
            ticker, scenarios, valuation_out.fair_value_low,
            valuation_out.fair_value_base, valuation_out.fair_value_high,
            ai_dcf_result=ai_dcf_result,
        )
        if needs_valuation and scenarios is not None else ""
    )
    direct_competitors_md = render_direct_competitors_table(competitive_out)
    market_share_md = render_market_share_table(ticker, scenarios, competitive_out) if needs_market_share else ""

    mechanical_base = None
    if scenarios is not None and scenarios.get("base") is not None:
        mechanical_base = scenarios["base"].intrinsic_value_per_share

    ml_comps_data = _get_ml_comps_data(ticker)
    ml_comps_ground_truth = ml_comps_data["ml_fair_price_mid"] if ml_comps_data is not None else None

    return valuation_tables_md, direct_competitors_md, market_share_md, mechanical_base, ml_comps_ground_truth


