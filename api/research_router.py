_background_tasks: dict[tuple[str, str], asyncio.Task] = {}

# Live one-line status per (ticker, model), polled by the frontend via /research/status.
# phase is one of: gathering_data, running_specialists, synthesizing, done, error, cancelled.
_task_status: dict[tuple[str, str], dict] = {}

_GENERATING_MD = (
    "## Generating Research Report for {ticker}...\n\n"
    "Gathering financials, valuation, SEC filings, earnings data, and web search, "
    "then running AI analysis.\n"
    "This takes approximately 60-90 seconds."
)


def _set_status(key: tuple[str, str], phase: str, message: str, error: Optional[str] = None) -> None:
    _task_status[key] = {"phase": phase, "message": message, "error": error}


async def _background_generate(ticker: str, model: str):
    key = (ticker, model)
    log.info("[%s] research: background task started (model=%s)", ticker, model)
    try:
        report, findings, valuation_tables_md, direct_competitors_md, market_share_md, dcf_reconciliation, \
            usage_tracker = await _run_research_agent(ticker, model, status_key=key)
        markdown = render_to_markdown(
            report, valuation_tables_md, direct_competitors_md, market_share_md, dcf_reconciliation,
            usage_tracker,
        )
        if findings:
            markdown += f"\n\n---\n\n*QC: {len(findings)} inconsistency(ies) detected — " + \
                "; ".join(findings) + "*"
        _cache_put(ticker, model, markdown)
        _set_status(key, "done", "Report ready.")
        log.info("[%s] research: report cached (%d chars)", ticker, len(markdown))
    except Exception as e:
        log.error("[%s] research: background task failed (model=%s): %s", ticker, model, e)
        _set_status(key, "error", f"Report generation failed: {e}", error=str(e))
    finally:
        _background_tasks.pop(key, None)


def _get_or_start(ticker: str, model: str, retry: bool = False) -> str:
    ticker = ticker.upper()
    key = (ticker, model)
    if md := _cache_get(ticker, model):
        _task_status.pop(key, None)
        return md

    if retry:
        _task_status.pop(key, None)

    status = _task_status.get(key)
    if status and status.get("phase") in ("error", "cancelled") and not retry:
        # Don't silently retry after a failure/cancellation — the user must explicitly
        # re-trigger generation. Without this, every poll would restart a fresh (and likely
        # identically-failing) generation forever without ever surfacing the error.
        return _GENERATING_MD.format(ticker=ticker)

    if key not in _background_tasks or _background_tasks[key].done():
        _background_tasks[key] = asyncio.create_task(_background_generate(ticker, model))
    return _GENERATING_MD.format(ticker=ticker)


