_FLOAT_PLACEHOLDER_STRINGS = {"n/a", "na", "none", "null", "-", "unavailable", ""}


def _coerce_optional_float(v):
    """Some models occasionally emit the string 'n/a' (or similar) instead of JSON null for an
    Optional[float] field when the underlying metric is genuinely undefined (e.g. P/E for an
    unprofitable company) — this crashes strict Pydantic validation on the whole report.
    Coerce known placeholder strings to None and parse numeric-looking strings; let anything
    else fall through to Pydantic's own error for a real type mismatch."""
    if v is None or isinstance(v, (int, float)):
        return v
    if isinstance(v, str):
        s = v.strip()
        if s.lower() in _FLOAT_PLACEHOLDER_STRINGS:
            return None
        try:
            return float(s.replace(",", "").replace("$", "").replace("%", ""))
        except ValueError:
            return None
    return v


