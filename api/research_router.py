def get_earnings_trend_summary(ticker: str, n_quarters: int = 4) -> str:
    """Fetch the last n cached earnings transcripts for a trailing-quarter trend narrative.

    Always probes AV for a quarter newer than the local cache first (mirroring the logic
    in earnings_router.py), then formats up to n_quarters cached transcripts, newest first.
    Degrades gracefully to however many quarters are actually cached (as few as 0).
    """
    ticker = ticker.upper()
    api_key = os.getenv("ALPHA_VANTAGE_API_KEY")

    conn = et.open_db(_EARNINGS_DB)
    try:
        limiter = RateLimiter(max_calls=70, period=60.0) if api_key else None
        et.refresh_latest_transcript(conn, ticker, api_key, limiter=limiter)
        quarters = et.get_last_n_transcripts(conn, ticker, n_quarters)
    finally:
        conn.close()

    if not quarters:
        if not api_key:
            return "[ERROR] ALPHA_VANTAGE_API_KEY not configured and no cached transcript available"
        return f"[ERROR] No earnings transcript found for {ticker}"

    blocks = [
        f"--- EARNINGS TRANSCRIPT — {ticker} {q} ---\n\n{txt[:_MAX_TRANSCRIPT_CHARS]}"
        for q, txt in quarters
    ]
    return f"EARNINGS TRANSCRIPTS — {ticker} (last {len(quarters)} quarters, newest first)\n\n" + \
        "\n\n".join(blocks)


def get_beat_miss_summary(ticker: str) -> str:
    """Last 8 quarters of reported vs. estimated EPS (AV EARNINGS function, 30-day cache)."""
    ticker = ticker.upper()
    api_key = os.getenv("ALPHA_VANTAGE_API_KEY")

    conn = et.open_db(_EARNINGS_DB)
    try:
        rows = et.get_cached_surprises(conn, ticker)
        if rows is None and api_key:
            try:
                fetched = et.fetch_surprises_from_av(ticker, api_key)
            except Exception:
                fetched = None
            if fetched:
                et.save_surprises(conn, ticker, fetched)
                rows = fetched
    finally:
        conn.close()

    if not rows:
        return "[INFO] No EPS beat/miss history available"

    lines = [f"EPS BEAT/MISS HISTORY — {ticker} (last {len(rows)} quarters, newest first)", ""]
    lines.append(f"{'Quarter End':<14}{'Reported EPS':>14}{'Estimated EPS':>15}{'Surprise':>12}")
    for r in rows:
        rep = f"${r['reported_eps']:.2f}" if r["reported_eps"] is not None else "n/a"
